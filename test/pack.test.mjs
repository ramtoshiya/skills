import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { test } from "node:test";

const root = fileURLToPath(new URL("../", import.meta.url));

test("the packed distribution is limited to shared content and runs without the checkout", async (t) => {
	const directory = mkdtempSync(join(tmpdir(), "ramtoshiya-pack-"));
	t.after(() => rmSync(directory, { recursive: true, force: true }));
	const workspace = join(directory, "source");
	mkdirSync(workspace);
	for (const path of ["package.json", "README.md", "docs", "plugins"]) {
		cpSync(join(root, path), join(workspace, path), { recursive: true });
	}
	writeFileSync(join(workspace, "private-local-fixture.txt"), "must not ship\n");
	const cache = join(workspace, "plugins/ramtoshiya/hooks/__pycache__");
	mkdirSync(cache, { recursive: true });
	writeFileSync(join(cache, "fixture.pyc"), "generated bytecode fixture\n");
	const [archive] = JSON.parse(execFileSync("npm", [
		"pack", "--json", "--ignore-scripts", "--pack-destination", directory,
	], { cwd: workspace, encoding: "utf8" }));
	for (const { path } of archive.files) {
		assert.ok(!path.includes("__pycache__/") && !path.endsWith(".pyc"), `Generated bytecode in distribution: ${path}`);
		assert.ok(
			path.startsWith("plugins/ramtoshiya/") ||
			["package.json", "README.md", "docs/agent-pack.md", "docs/hooks.md"].includes(path),
			`Unrelated/private content in distribution: ${path}`,
		);
	}
	execFileSync("tar", ["-xf", join(directory, archive.filename), "-C", directory]);
	const installed = join(directory, "package");
	const manifest = JSON.parse(readFileSync(join(installed, "package.json"), "utf8"));
	assert.equal(manifest.pi.extensions.length, 1);
	const { default: register } = await import(pathToFileURL(join(installed, manifest.pi.extensions[0])).href);
	let handler;
	register({ on(event, callback) { if (event === "tool_call") handler = callback; } });
	const check = (command) => handler(
		{ type: "tool_call", toolName: "bash", toolCallId: "packed", input: { command } },
		{ cwd: dirname(installed) },
	);
	const denied = await check("python3 -V");
	assert.equal(denied.block, true);
	assert.match(denied.reason, /Bare Python\/pip/);
	assert.equal(await check("git status"), undefined);
});
